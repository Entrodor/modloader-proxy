#!/usr/bin/env python3
"""Print the named exports of one or more PE files (union of all inputs).

  python tools/dump_exports.py -o exports/dbghelp.txt C:\\Windows\\System32\\dbghelp.dll C:\\Windows\\SysWOW64\\dbghelp.dll

Pass BOTH the 64-bit (System32) and 32-bit (SysWOW64) DLL when you can: export
lists can differ slightly between architectures, and the union is safe for both.
Use -o instead of '>' (PowerShell's '>' writes UTF-16, which breaks other tools).
"""
import struct
import sys


def read_exports(path):
    d = open(path, "rb").read()
    if d[:2] != b"MZ":
        raise ValueError("not a PE file")
    pe = struct.unpack_from("<I", d, 0x3C)[0]
    if d[pe:pe + 4] != b"PE\0\0":
        raise ValueError("bad PE signature")
    nsec = struct.unpack_from("<H", d, pe + 6)[0]
    optsz = struct.unpack_from("<H", d, pe + 20)[0]
    opt = pe + 24
    magic = struct.unpack_from("<H", d, opt)[0]
    ddir = opt + (112 if magic == 0x20B else 96)
    exp_rva, _ = struct.unpack_from("<II", d, ddir)
    if exp_rva == 0:
        return [], 0

    secs = []
    for i in range(nsec):
        off = opt + optsz + 40 * i
        vsize, va, rawsize, rawptr = struct.unpack_from("<IIII", d, off + 8)
        secs.append((va, max(vsize, rawsize), rawptr))

    def off_of(rva):
        for va, size, raw in secs:
            if va <= rva < va + size:
                return rva - va + raw
        raise ValueError("bad RVA 0x%x" % rva)

    def cstr(o):
        return d[o:d.index(b"\0", o)].decode("ascii", "replace")

    e = off_of(exp_rva)
    nfuncs, nnames = struct.unpack_from("<II", d, e + 20)
    names_rva = struct.unpack_from("<I", d, e + 32)[0]
    base = off_of(names_rva)
    names = [cstr(off_of(struct.unpack_from("<I", d, base + 4 * i)[0])) for i in range(nnames)]
    return names, max(0, nfuncs - nnames)


def main(argv):
    out = None
    if len(argv) >= 2 and argv[0] == "-o":
        out, argv = argv[1], argv[2:]
    if not argv:
        sys.exit(__doc__)
    merged, seen = [], set()
    for p in argv:
        names, unnamed = read_exports(p)
        if unnamed:
            print("warning: %s has %d ordinal-only export(s); they cannot be proxied by name"
                  % (p, unnamed), file=sys.stderr)
        for n in names:
            if n not in seen:
                seen.add(n)
                merged.append(n)
    text = "# generated by tools/dump_exports.py from: %s\n%s\n" % (
        ", ".join(a.replace("\\", "/") for a in argv), "\n".join(merged))
    if out:
        with open(out, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("wrote %d names to %s" % (len(merged), out))
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main(sys.argv[1:])
