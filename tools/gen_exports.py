#!/usr/bin/env python3
"""Generate C++ headers from exports/*.txt (one export name per line, '#' = comment).

Each file name selects a proxy target: exports/dbghelp.txt -> dbghelp.dll.
Run automatically by the Makefile.
"""
import pathlib
import re
import sys

IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
RESERVED = {"DllMain"}


def x_macro(name, names):
    rows = [" ".join("X(%s)" % n for n in names[i:i + 4]) for i in range(0, len(names), 4)]
    return "#define %s(X) \\\n    %s\n\n" % (name, " \\\n    ".join(rows))


def main():
    if len(sys.argv) != 3:
        sys.exit("usage: gen_exports.py <exports dir> <output dir>")
    src, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
    out.mkdir(parents=True, exist_ok=True)

    dlls = {}
    for f in sorted(src.glob("*.txt")):
        names = []
        for line in f.read_text(encoding="utf-8-sig").splitlines():
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            if not IDENT.match(line) or line in RESERVED:
                print("warning: %s: skipping unsupported export %r" % (f.name, line), file=sys.stderr)
                continue
            if line not in names:
                names.append(line)
        stem = f.stem.lower()
        dll = stem if stem.endswith(".dll") else stem + ".dll"
        if names:
            dlls[dll] = names
    if not dlls:
        sys.exit("error: no export lists found in %s" % src)

    union, seen = [], set()
    for names in dlls.values():
        for n in names:
            if n not in seen:
                seen.add(n)
                union.append(n)

    header = ["// GENERATED by tools/gen_exports.py - do not edit.\n#pragma once\n\n"]
    for i, (dll, names) in enumerate(dlls.items()):
        header.append("// %s\n" % dll)
        header.append(x_macro("LIST_DLL_%d" % i, names))
    header.append("// union of all names (one stub + one pointer each)\n")
    header.append(x_macro("LIST_ALL", union))
    (out / "proxy_lists_gen.h").write_text("".join(header), encoding="utf-8")

    code = ["// GENERATED by tools/gen_exports.py - do not edit.\n"]
    for i in range(len(dlls)):
        code.append("void Bind_%d(HMODULE real) { LIST_DLL_%d(BIND) }\n" % (i, i))
    code.append("\nconst ProxyTarget kTargets[] = {\n")
    for i, dll in enumerate(dlls):
        code.append('    {L"%s", Bind_%d},\n' % (dll, i))
    code.append("};\n")
    (out / "proxy_targets_gen.inc").write_text("".join(code), encoding="utf-8")

    (out / "supported_dlls.txt").write_text(
        "Supported proxy names (rename modloader-proxy.dll to one of these):\n\n"
        + "".join("  %s\n" % d for d in dlls), encoding="utf-8")

    print("gen_exports: %d proxy targets, %d unique exports" % (len(dlls), len(union)))


if __name__ == "__main__":
    main()
